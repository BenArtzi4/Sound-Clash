"""Write tests/smoke/setlist_timing_selfcheck.sql from migration 060.

The timing check installs migration 060's new function bodies inside a
rolled-back DO block (spec §10 of docs/planning/2026-11-24-custom-setlist-design.md).
Those bodies must be byte-identical to 060's, so they are never copied by hand:
this script cuts each `CREATE OR REPLACE FUNCTION <name>(... $$;` block out of
db/migrations/060_game_song_pool.sql and puts it in the template below.

    python tests/smoke/gen_setlist_timing.py          # (re)write the .sql
    python tests/smoke/gen_setlist_timing.py --check  # exit 1 if it is stale

After any change to 060's pick_next_pool_song, 4-argument select_next_song or
peek_next_song, run it again and commit the new .sql. Standard library only.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MIGRATION = ROOT / "db" / "migrations" / "060_game_song_pool.sql"
OUTPUT = ROOT / "tests" / "smoke" / "setlist_timing_selfcheck.sql"

# The DO block's own dollar-quote tags. None may occur inside an embedded body.
TAGS = ("$timing$", "$m0$", "$m1$", "$m2$", "$m3$")

# (placeholder in TEMPLATE, function name, text that pins the overload)
BLOCKS = (
    ("@@PICK_NEXT_POOL_SONG@@", "pick_next_pool_song", "(p_game_code text)"),
    ("@@SELECT_NEXT_SONG@@", "select_next_song", "p_expected_round integer"),
    ("@@PEEK_NEXT_SONG@@", "peek_next_song", "p_manager_token uuid\n)"),
)

TEMPLATE = """\
-- tests/smoke/setlist_timing_selfcheck.sql
-- GENERATED by tests/smoke/gen_setlist_timing.py from
-- db/migrations/060_game_song_pool.sql. Do not edit by hand: change the
-- generator or migration 060, then run `python tests/smoke/gen_setlist_timing.py`.
--
-- Custom setlists, phase 1, no-regression proof 2 of 2 (spec §10 of
-- docs/planning/2026-11-24-custom-setlist-design.md): do normal genre games
-- get slower with migration 060, and is the custom-game pool picker fast?
-- Run it on production BEFORE migration 060 is applied there.
--
-- What it measures, all inside ONE DO block that ends by raising an error, so
-- every row and every object it makes is rolled back:
--   1. Today's functions (mig 057). Synthetic games that play the 8 genres
--      with the most available songs: per round one timed
--      peek_next_song(code, token) and one timed guarded
--      select_next_song(code, token, NULL, <current round_number>), 20 rounds
--      per game, a fresh game every 20 rounds, 200 timed calls of each. Before
--      them, 5 untimed warm-up rounds on a game of their own.
--   2. Migration 060 installed with EXECUTE: game_setlists and game_song_pool
--      WITHOUT foreign keys (same columns, primary keys and CHECKs as 060,
--      nothing else), and the exact bodies of pick_next_pool_song, the
--      4-argument select_next_song and peek_next_song cut from 060 by the
--      generator. Then step 1 again on new fresh games.
--   3. One custom game: a ready game_setlists row and 300 random available
--      catalog songs in game_song_pool (150 tier 1, 150 tier 2), 10 rounds
--      played through the new select_next_song, 5 warm-up picks, then 200
--      timed pick_next_pool_song(code) calls.
--   Each time is a clock_timestamp() difference, in ms per call.
--
-- Pass marks (spec §10), all on the averages:
--   new_peek   <= old_peek + 1
--   new_select <= old_select + 1
--   pool_pick  <  10
--
-- Output: the run always ends with an error. Its message is ONE line:
--   TIMING_ROLLBACK old_peek=A new_peek=B old_select=C new_select=D pool_pick=E
--     old_peek_p95=.. new_peek_p95=.. old_select_p95=.. new_select_p95=..
--     pool_pick_p95=.. verdict=PASS|FAIL calls=200 genre_songs=N catalog=N
--     elapsed_s=S defs=select:<md5>,peek:<md5>,pool:<md5>
--   (averages and p95 in ms, 3 decimals; verdict applies the pass marks above;
--   defs are the first 12 hex digits of md5(pg_get_functiondef(...)) of the
--   three bodies that were timed: after 060 is applied, the same md5s of the
--   live functions must match, see step 4 below.)
--   PASS of the RUN means the message starts with "TIMING_ROLLBACK ". Any
--   other error is a FAILED run, never a result: TIMING_SETUP_FAILED and
--   TIMING_ABORTED say why; "canceling statement due to lock timeout" means
--   something else held a lock (the run gave up after 1 s instead of queueing);
--   "canceling statement due to statement timeout" means it ran too long.
--
-- How to run (production, from a tree that is linked to the project):
--   0. From the repo root, prove this file still holds migration 060's
--      bodies; it must print "... is up to date":
--        python tests/smoke/gen_setlist_timing.py --check
--   1. Live-game check, and run this only when it returns 0 (or the
--      maintainer accepts the games that are live; a "live" game can be
--      another session's harness, so watch round_number for a few minutes):
--        SELECT count(*) FROM active_games WHERE ended_at IS NULL AND expires_at > now();
--   2. supabase db query --linked -f "C:/abs/path/tests/smoke/setlist_timing_selfcheck.sql"
--   3. Leftover check, as one statement; every column must be 0 or NULL:
--        SELECT (SELECT count(*) FROM active_games WHERE game_code LIKE 'ZT0%') AS games,
--               (SELECT count(*) FROM game_rounds  WHERE game_code LIKE 'ZT0%') AS rounds,
--               (SELECT count(*) FROM game_secrets WHERE game_code LIKE 'ZT0%') AS secrets,
--               to_regclass('public.game_setlists') AS setlists,
--               to_regclass('public.game_song_pool') AS pool,
--               to_regprocedure('public.pick_next_pool_song(text)') AS picker;
--   4. Later, once migration 060 is applied, check that what was timed is
--      what was applied. One statement; its three values must equal the
--      run's defs= values (select, peek, pool, in that order):
--        SELECT left(md5(pg_get_functiondef('public.select_next_song(text,uuid,uuid,integer)'::regprocedure)),12) AS select_next_song,
--               left(md5(pg_get_functiondef('public.peek_next_song(text,uuid)'::regprocedure)),12) AS peek_next_song,
--               left(md5(pg_get_functiondef('public.pick_next_pool_song(text)'::regprocedure)),12) AS pick_next_pool_song;
--   The synthetic game codes are ZT0001, ZT0002, ... The backend's code
--   alphabet has no 0 (backend/app/services/codes.py), so no real game can
--   have one; match them with LIKE 'ZT0%', not 'ZT%' (a real code can start
--   with ZT).
--
-- Locks (Ruling A): plain INSERT/UPDATE on the synthetic rows only, which takes
-- ROW EXCLUSIVE on active_games, game_secrets and game_rounds, the mode every
-- live buzz_in / scoring UPDATE takes too, so they never wait for each other.
-- The foreign keys of the synthetic rounds take FOR KEY SHARE row locks on the
-- songs they point at, exactly as a real round does. One advisory lock per
-- synthetic game code. No DDL on an existing table: the two new tables have no
-- foreign keys, because CREATE TABLE ... REFERENCES active_games would hold
-- SHARE ROW EXCLUSIVE on active_games until the rollback and stall every live
-- buzz. CREATE OR REPLACE of select_next_song / peek_next_song stays invisible
-- to other sessions until a commit that never comes: live hosts keep running
-- today's bodies. Nothing is committed, so Realtime sends nothing.
-- lock_timeout 1 s turns any unexpected wait into an error instead of a queue;
-- statement_timeout 55 s and the block's own 50 s deadline keep the run under
-- the 100 s cut of the CLI's proxy (it takes about 13 s on ~1,700 songs;
-- local runs 12.4–12.7 s).

SET statement_timeout = '55s';
SET lock_timeout = '1s';

DO $timing$
DECLARE
  c_calls       constant integer  := 200;  -- timed calls of each kind
  c_rounds      constant integer  := 20;   -- rounds per synthetic genre game
  c_warmup      constant integer  := 5;    -- untimed warm-up rounds / picks
  c_pool_size   constant integer  := 300;  -- 150 tier 1 + 150 tier 2
  c_pool_played constant integer  := 10;   -- rounds played before the picks
  c_deadline    constant interval := interval '50 seconds';
  v_start        timestamptz := clock_timestamp();
  v_t0           timestamptz;
  v_ms           double precision;
  v_genres       uuid[];
  v_genre_songs  integer;
  v_catalog      integer;
  v_seq          integer := 0;
  v_phase        integer;
  v_code         text;
  v_token        uuid;
  v_round        integer;
  v_song         uuid;
  v_n            integer;
  v_peek_ms      double precision[];
  v_select_ms    double precision[];
  v_old_peek     double precision[];
  v_old_select   double precision[];
  v_new_peek     double precision[];
  v_new_select   double precision[];
  v_pool_ms      double precision[] := '{}';
  v_old_peek_avg numeric;   v_old_peek_p95 numeric;
  v_new_peek_avg numeric;   v_new_peek_p95 numeric;
  v_old_sel_avg  numeric;   v_old_sel_p95  numeric;
  v_new_sel_avg  numeric;   v_new_sel_p95  numeric;
  v_pool_avg     numeric;   v_pool_p95     numeric;
  v_verdict      text;
  v_defs         text;
BEGIN
  -- Name resolution of everything below, the CREATEs included: public only.
  PERFORM set_config('search_path', 'public', true);
  PERFORM set_config('lock_timeout', '1s', true);

  IF to_regclass('public.game_setlists') IS NOT NULL
     OR to_regclass('public.game_song_pool') IS NOT NULL
     OR to_regprocedure('public.pick_next_pool_song(text)') IS NOT NULL THEN
    RAISE EXCEPTION 'TIMING_SETUP_FAILED migration 060 is already applied here; this check measures the database before it';
  END IF;

  IF EXISTS (SELECT 1 FROM active_games WHERE game_code LIKE 'ZT0%') THEN
    RAISE EXCEPTION 'TIMING_SETUP_FAILED a game with a ZT0 code already exists';
  END IF;

  -- The 8 genres with the most available songs.
  SELECT array_agg(t.gid ORDER BY t.n DESC, t.gid)
    INTO v_genres
    FROM (
      SELECT sg.genre_id AS gid, count(*) AS n
        FROM song_genres sg
        JOIN songs s ON s.id = sg.song_id
       WHERE s.unavailable_at IS NULL
       GROUP BY sg.genre_id
       ORDER BY count(*) DESC, sg.genre_id
       LIMIT 8
    ) t;

  IF coalesce(cardinality(v_genres), 0) < 8 THEN
    RAISE EXCEPTION 'TIMING_SETUP_FAILED fewer than 8 genres have available songs';
  END IF;

  SELECT count(DISTINCT sg.song_id)
    INTO v_genre_songs
    FROM song_genres sg
    JOIN songs s ON s.id = sg.song_id
   WHERE sg.genre_id = ANY (v_genres)
     AND s.unavailable_at IS NULL;

  SELECT count(*) INTO v_catalog FROM songs s WHERE s.unavailable_at IS NULL;

  -- Phase 1 = today's bodies, phase 2 = migration 060's.
  FOR v_phase IN 1..2 LOOP
    IF v_phase = 2 THEN
      -- Migration 060's tables WITHOUT foreign keys (Ruling A).
      EXECUTE $m0$
        CREATE TABLE public.game_setlists (
          game_code  text PRIMARY KEY,
          ready      boolean NOT NULL DEFAULT false,
          list_total integer NOT NULL DEFAULT 0,
          created_at timestamptz NOT NULL DEFAULT now()
        )
      $m0$;
      EXECUTE $m0$
        CREATE TABLE public.game_song_pool (
          game_code text NOT NULL,
          song_id   uuid NOT NULL,
          tier      smallint NOT NULL CHECK (tier IN (1, 2)),
          PRIMARY KEY (game_code, song_id)
        )
      $m0$;

      -- The bodies below are cut from migration 060 byte for byte.
      EXECUTE $m1$@@PICK_NEXT_POOL_SONG@@$m1$;
      EXECUTE $m2$@@SELECT_NEXT_SONG@@$m2$;
      EXECUTE $m3$@@PEEK_NEXT_SONG@@$m3$;
    END IF;

    v_peek_ms := '{}';
    v_select_ms := '{}';
    v_code := NULL;

    FOR k IN 1 .. c_warmup + c_calls LOOP
      -- A fresh game for the warm-up, for the first timed round, and after
      -- every c_rounds rounds.
      IF v_code IS NULL OR k = c_warmup + 1 OR v_round >= c_rounds THEN
        v_seq := v_seq + 1;
        v_code := 'ZT0' || lpad(v_seq::text, 3, '0');
        INSERT INTO active_games (game_code, status, selected_genres)
        VALUES (v_code, 'waiting', v_genres);
        SELECT gs.manager_token INTO STRICT v_token
          FROM game_secrets gs
         WHERE gs.game_code = v_code;
        v_round := 0;
      END IF;

      IF clock_timestamp() - v_start > c_deadline THEN
        RAISE EXCEPTION 'TIMING_ABORTED past the deadline in phase % at call %', v_phase, k;
      END IF;

      v_t0 := clock_timestamp();
      SELECT p.song_id INTO v_song
        FROM peek_next_song(v_code, v_token) p;
      v_ms := 1000 * extract(epoch FROM clock_timestamp() - v_t0);
      IF v_song IS NULL THEN
        RAISE EXCEPTION 'TIMING_SETUP_FAILED peek found no song for game % at round %', v_code, v_round;
      END IF;
      IF k > c_warmup THEN
        v_peek_ms := v_peek_ms || v_ms;
      END IF;

      v_t0 := clock_timestamp();
      SELECT r.round_number INTO STRICT v_round
        FROM select_next_song(v_code, v_token, NULL::uuid, v_round) r;
      v_ms := 1000 * extract(epoch FROM clock_timestamp() - v_t0);
      IF k > c_warmup THEN
        v_select_ms := v_select_ms || v_ms;
      END IF;
    END LOOP;

    IF v_phase = 1 THEN
      v_old_peek := v_peek_ms;
      v_old_select := v_select_ms;
    ELSE
      v_new_peek := v_peek_ms;
      v_new_select := v_select_ms;
    END IF;
  END LOOP;

  -- Phase 3: the pool picker on one custom game.
  v_seq := v_seq + 1;
  v_code := 'ZT0' || lpad(v_seq::text, 3, '0');
  INSERT INTO active_games (game_code, status) VALUES (v_code, 'waiting');
  SELECT gs.manager_token INTO STRICT v_token
    FROM game_secrets gs
   WHERE gs.game_code = v_code;

  INSERT INTO game_setlists (game_code, ready, list_total)
  VALUES (v_code, true, c_pool_size / 2);
  INSERT INTO game_song_pool (game_code, song_id, tier)
  SELECT v_code, x.id, CASE WHEN x.rn <= c_pool_size / 2 THEN 1 ELSE 2 END
    FROM (
      SELECT s.id, row_number() OVER (ORDER BY random()) AS rn
        FROM songs s
       WHERE s.unavailable_at IS NULL
    ) x
   WHERE x.rn <= c_pool_size;
  GET DIAGNOSTICS v_n = ROW_COUNT;
  IF v_n <> c_pool_size THEN
    RAISE EXCEPTION 'TIMING_SETUP_FAILED only % available songs for a % song pool', v_n, c_pool_size;
  END IF;

  v_round := 0;
  FOR k IN 1 .. c_pool_played LOOP
    SELECT r.round_number INTO STRICT v_round
      FROM select_next_song(v_code, v_token, NULL::uuid, v_round) r;
  END LOOP;

  -- The new bodies really are the ones running: the custom game played its
  -- list (tier 1), and peek picks from it (today's peek would raise
  -- no_genres_selected on a game with no genres).
  SELECT count(*) INTO v_n
    FROM game_rounds gr
    JOIN game_song_pool gp ON gp.game_code = gr.game_code AND gp.song_id = gr.song_id
   WHERE gr.game_code = v_code
     AND gp.tier = 1;
  IF v_n <> c_pool_played THEN
    RAISE EXCEPTION 'TIMING_SETUP_FAILED the custom game played % list songs in % rounds', v_n, c_pool_played;
  END IF;
  SELECT p.song_id INTO v_song FROM peek_next_song(v_code, v_token) p;
  IF NOT EXISTS (
    SELECT 1 FROM game_song_pool gp
     WHERE gp.game_code = v_code AND gp.song_id = v_song AND gp.tier = 1
  ) THEN
    RAISE EXCEPTION 'TIMING_SETUP_FAILED peek on the custom game did not pick a list song';
  END IF;

  FOR k IN 1 .. c_warmup + c_calls LOOP
    IF clock_timestamp() - v_start > c_deadline THEN
      RAISE EXCEPTION 'TIMING_ABORTED past the deadline in phase 3 at call %', k;
    END IF;

    v_t0 := clock_timestamp();
    v_song := pick_next_pool_song(v_code);
    v_ms := 1000 * extract(epoch FROM clock_timestamp() - v_t0);
    IF v_song IS NULL THEN
      RAISE EXCEPTION 'TIMING_SETUP_FAILED the pool picker found no song';
    END IF;
    IF k > c_warmup THEN
      v_pool_ms := v_pool_ms || v_ms;
    END IF;
  END LOOP;

  SELECT round(avg(u.x)::numeric, 3),
         round((percentile_cont(0.95) WITHIN GROUP (ORDER BY u.x))::numeric, 3)
    INTO v_old_peek_avg, v_old_peek_p95
    FROM unnest(v_old_peek) AS u(x);
  SELECT round(avg(u.x)::numeric, 3),
         round((percentile_cont(0.95) WITHIN GROUP (ORDER BY u.x))::numeric, 3)
    INTO v_new_peek_avg, v_new_peek_p95
    FROM unnest(v_new_peek) AS u(x);
  SELECT round(avg(u.x)::numeric, 3),
         round((percentile_cont(0.95) WITHIN GROUP (ORDER BY u.x))::numeric, 3)
    INTO v_old_sel_avg, v_old_sel_p95
    FROM unnest(v_old_select) AS u(x);
  SELECT round(avg(u.x)::numeric, 3),
         round((percentile_cont(0.95) WITHIN GROUP (ORDER BY u.x))::numeric, 3)
    INTO v_new_sel_avg, v_new_sel_p95
    FROM unnest(v_new_select) AS u(x);
  SELECT round(avg(u.x)::numeric, 3),
         round((percentile_cont(0.95) WITHIN GROUP (ORDER BY u.x))::numeric, 3)
    INTO v_pool_avg, v_pool_p95
    FROM unnest(v_pool_ms) AS u(x);

  IF cardinality(v_old_peek) <> c_calls OR cardinality(v_new_peek) <> c_calls
     OR cardinality(v_old_select) <> c_calls OR cardinality(v_new_select) <> c_calls
     OR cardinality(v_pool_ms) <> c_calls THEN
    RAISE EXCEPTION 'TIMING_SETUP_FAILED a phase did not make % timed calls', c_calls;
  END IF;

  v_verdict := CASE
    WHEN v_new_peek_avg <= v_old_peek_avg + 1
     AND v_new_sel_avg <= v_old_sel_avg + 1
     AND v_pool_avg < 10
    THEN 'PASS' ELSE 'FAIL' END;

  v_defs := 'select:'
    || left(md5(pg_get_functiondef('public.select_next_song(text,uuid,uuid,integer)'::regprocedure)), 12)
    || ',peek:'
    || left(md5(pg_get_functiondef('public.peek_next_song(text,uuid)'::regprocedure)), 12)
    || ',pool:'
    || left(md5(pg_get_functiondef('public.pick_next_pool_song(text)'::regprocedure)), 12);

  RAISE EXCEPTION '%', format(
    'TIMING_ROLLBACK old_peek=%s new_peek=%s old_select=%s new_select=%s pool_pick=%s'
    ' old_peek_p95=%s new_peek_p95=%s old_select_p95=%s new_select_p95=%s pool_pick_p95=%s'
    ' verdict=%s calls=%s genre_songs=%s catalog=%s elapsed_s=%s defs=%s',
    v_old_peek_avg, v_new_peek_avg, v_old_sel_avg, v_new_sel_avg, v_pool_avg,
    v_old_peek_p95, v_new_peek_p95, v_old_sel_p95, v_new_sel_p95, v_pool_p95,
    v_verdict, c_calls, v_genre_songs, v_catalog,
    round(extract(epoch FROM clock_timestamp() - v_start)::numeric, 1),
    v_defs);
END
$timing$;
"""


def extract(sql: str, name: str, pin: str) -> str:
    """The one `CREATE OR REPLACE FUNCTION name(... $$;` block of 060."""
    pattern = re.compile(
        r"^CREATE OR REPLACE FUNCTION " + re.escape(name) + r"\(.*?\$\$;$",
        re.DOTALL | re.MULTILINE,
    )
    found = pattern.findall(sql)
    if len(found) != 1:
        raise SystemExit(f"{MIGRATION.name}: expected 1 {name} block, found {len(found)}")
    block = found[0]
    if pin not in block:
        raise SystemExit(f"{name}: the block does not contain {pin!r} (wrong overload?)")
    if block.count("$$") != 2:
        raise SystemExit(f"{name}: expected exactly the opening and closing $$")
    for tag in TAGS:
        if tag in block:
            raise SystemExit(f"{name}: the body contains the dollar tag {tag}")
    if block not in sql:
        raise SystemExit(f"{name}: the block is not a byte-identical slice of 060")
    return block


def render() -> str:
    raw = MIGRATION.read_bytes().decode("utf-8")
    if "\r" in raw:
        raise SystemExit(f"{MIGRATION.name} has CR characters; expected LF line endings")
    out = TEMPLATE
    for placeholder, name, pin in BLOCKS:
        if out.count(placeholder) != 1:
            raise SystemExit(f"template: {placeholder} must occur exactly once")
        out = out.replace(placeholder, extract(raw, name, pin))
    if "@@" in out:
        raise SystemExit("template: an unreplaced @@ placeholder is left")
    return out


def main() -> int:
    text = render()
    rel = OUTPUT.relative_to(ROOT).as_posix()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_bytes().decode("utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{rel} is stale: run tests/smoke/gen_setlist_timing.py")
            return 1
        print(f"{rel} is up to date")
        return 0
    with OUTPUT.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
