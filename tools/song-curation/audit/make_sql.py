#!/usr/bin/env python3
"""Turn approved review decisions into one guarded, all-or-nothing SQL file.

Reads items.json + decisions.json (the batch folder). Writes apply.sql,
apply_dryrun.sql (same, but ends in RAISE EXCEPTION 'DRYRUN_OK_ROLLBACK') and
apply_plan.json, and prints a summary. It does NOT touch any database.

Guards inside the SQL (one DO block, so any failure rolls everything back):
- every UPDATE/DELETE matches the row's reviewed values (title, artist,
  youtube_id); 0 rows touched -> exception "row changed since review"
- a new youtube_id that another song already uses -> exception
- genre slugs are resolved by slug and must all exist
- a changed youtube_id clears unavailable_at (a new video is presumed playable)

usage (from the batch folder): python <tools>/audit/make_sql.py
"""
from __future__ import annotations
import json, sys
from pathlib import Path

HERE = Path.cwd()  # the batch folder
items = {i["id"]: i for i in json.loads((HERE / "items.json").read_text(encoding="utf-8"))["items"]}
dec = json.loads((HERE / "decisions.json").read_text(encoding="utf-8")) if (HERE / "decisions.json").exists() else {}


def q(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


songs: dict = {}
problems: list[str] = []


def touch(s):
    return songs.setdefault(s["id"], {"song": s, "set": {}, "delete": False, "items": []})


for iid, d in dec.items():
    if not d or d.get("status") != "approved":
        continue
    it = items.get(iid)
    if not it:
        problems.append(f"decision for unknown item {iid}")
        continue
    p = it.get("proposal") or {}
    if it["kind"] in ("duplicate", "maybe_dup"):
        keep = d.get("keep") or p.get("keep")
        if not keep:
            problems.append(f"{iid}: approved without a song to keep")
            continue
        for s in it["songs"]:
            if s["id"] != keep:
                e = touch(s)
                e["delete"] = True
                e["items"].append(iid)
        kept = next(s for s in it["songs"] if s["id"] == keep)
        # the page saves the card's full final state; fall back to the proposal
        fields = dict(d["fields"]) if "fields" in d else dict(p.get("fields") or {})
        e = touch(kept)
        e["items"].append(iid)
        for f, v in fields.items():
            e["set"].setdefault(f, []).append((v, iid))
        continue
    s = it["songs"][0]
    e = touch(s)
    e["items"].append(iid)
    if p.get("action") == "delete":
        e["delete"] = True
        continue
    fields = dict(d["fields"]) if "fields" in d else dict(p.get("fields") or {})
    for f, v in fields.items():
        cur = sorted(s["genres"]) if f == "genres" else s.get(f)
        nv = sorted(v) if f == "genres" else v
        if nv == cur:
            continue
        e["set"].setdefault(f, []).append((nv, iid))

final = {}
for sid, e in songs.items():
    s = e["song"]
    if e["delete"]:
        final[sid] = {"song": s, "delete": True, "set": {}}
        continue
    out = {}
    for f, vals in e["set"].items():
        uniq = {json.dumps(v, ensure_ascii=False) for v, _ in vals}
        if len(uniq) > 1:
            problems.append(f"{s['title']} — {s['artist']}: conflicting {f}: {' vs '.join(uniq)} (items {[i for _, i in vals]})")
            continue
        out[f] = vals[0][0]
    cur = {"genres": sorted(s["genres"])}
    out = {f: v for f, v in out.items() if v != (cur.get(f) if f == "genres" else s.get(f))}
    if out:
        final[sid] = {"song": s, "delete": False, "set": out}

# a new video id must not collide with another song's video (unique index)
new_ids = {}
for sid, e in final.items():
    vid = e["set"].get("youtube_id")
    if vid:
        if vid in new_ids:
            problems.append(f"two songs would get video {vid}")
        new_ids[vid] = sid

if problems:
    print("PROBLEMS — fix these in the review page first:")
    for p in problems:
        print("  -", p)
    sys.exit(1)

lines = ["-- Catalog audit fixes, generated by make_sql.py. One DO block: all or nothing.",
         "DO $audit$", "DECLARE n int; BEGIN"]
for vid, sid in new_ids.items():
    lines.append(f"  IF EXISTS (SELECT 1 FROM songs WHERE youtube_id = {q(vid)} AND id <> {q(sid)}::uuid"
                 f" AND id NOT IN (SELECT unnest(ARRAY[{','.join(q(x) for x, e in final.items() if e['delete']) or 'NULL'}]::uuid[])))"
                 f" THEN RAISE EXCEPTION 'video {vid} already used by another song'; END IF;")
dels = [(sid, e) for sid, e in final.items() if e["delete"]]
ups = [(sid, e) for sid, e in final.items() if not e["delete"]]
for sid, e in dels:
    s = e["song"]
    lines.append(f"  DELETE FROM songs WHERE id = {q(sid)}::uuid AND youtube_id = {q(s['youtube_id'])};")
    lines.append(f"  GET DIAGNOSTICS n = ROW_COUNT; IF n <> 1 THEN RAISE EXCEPTION 'delete: row changed since review: %', {q(sid)}; END IF;")
for sid, e in ups:
    s, st = e["song"], e["set"]
    cols = []
    for f in ("title", "artist", "youtube_id", "start_time", "release_year"):
        if f in st:
            cols.append(f"{f} = {q(st[f])}")
    if "youtube_id" in st:
        cols.append("unavailable_at = NULL")
    guard = f"id = {q(sid)}::uuid AND title = {q(s['title'])} AND artist = {q(s['artist'])} AND youtube_id = {q(s['youtube_id'])}"
    if cols:
        lines.append(f"  UPDATE songs SET {', '.join(cols)} WHERE {guard};")
        lines.append(f"  GET DIAGNOSTICS n = ROW_COUNT; IF n <> 1 THEN RAISE EXCEPTION 'update: row changed since review: %', {q(sid)}; END IF;")
    if "genres" in st:
        g = st["genres"]
        if not g:
            lines.append(f"  RAISE EXCEPTION 'empty genre list for %', {q(sid)};")
        arr = "ARRAY[" + ",".join(q(x) for x in g) + "]::text[]"
        lines.append(f"  IF (SELECT count(*) FROM genres WHERE slug = ANY({arr})) <> {len(g)} THEN RAISE EXCEPTION 'unknown genre in %', {arr}; END IF;")
        lines.append(f"  DELETE FROM song_genres WHERE song_id = {q(sid)}::uuid;")
        lines.append(f"  INSERT INTO song_genres (song_id, genre_id) SELECT {q(sid)}::uuid, id FROM genres WHERE slug = ANY({arr});")
(HERE / "apply_dryrun.sql").write_text(
    "\n".join(lines + ["  RAISE EXCEPTION 'DRYRUN_OK_ROLLBACK';", "END $audit$;", ""]), encoding="utf-8", newline="\n")
lines += ["END $audit$;", ""]
(HERE / "apply.sql").write_text("\n".join(lines), encoding="utf-8", newline="\n")
plan = [{"song_id": sid, "was": {k: e["song"][k] for k in ("title", "artist", "youtube_id", "start_time", "release_year", "genres")},
         "delete": e["delete"], "set": e["set"]} for sid, e in final.items()]
(HERE / "apply_plan.json").write_text(json.dumps(plan, ensure_ascii=False, indent=1), encoding="utf-8")
from collections import Counter  # noqa: E402
fc = Counter(f for _, e in ups for f in e["set"])
print(f"apply.sql: {len(dels)} deletes, {len(ups)} updates; fields changed: {dict(fc)}")
